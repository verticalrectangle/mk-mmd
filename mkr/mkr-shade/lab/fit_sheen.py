"""Write src/sheen_table.rs from the lab's sheen renders: EEVEE's Principled sheen albedo over (cos_theta, roughness).

    python3 mkr/mkr-shade/lab/fit_sheen.py LAB_DIR

The `closure_sheen_rNNNN` cases render a black, specular-free Principled BSDF with sheen weight 1 and sheen roughness
NNNN / 1000 under a uniform white world: EEVEE adds the sheen to the diffuse closure, so each row shows the albedo at its
N.I times the world's diffuse response, which `closure_diffuse` measures (colour (0.8, 0.5, 0.2)). The table keeps the
measured cos_theta and roughness positions (piecewise linear between them, clamped outside)."""
import glob
import json
import os
import sys

import numpy as np


def main():
    lab = sys.argv[1]
    n = 48
    rows = np.array(json.load(open(os.path.join(lab, "closure_diffuse.json")))["rows"])
    diffuse = np.fromfile(os.path.join(lab, "closure_diffuse.ref.bin"), np.float32).reshape(n, n, 4)
    gain = diffuse[:, :, 0].mean(axis=1) / 0.8
    rough, curves = [], []
    for path in sorted(glob.glob(os.path.join(lab, "closure_sheen_r[0-9][0-9][0-9][0-9].ref.bin"))):
        r = int(os.path.basename(path)[len("closure_sheen_r"):][:4]) / 1000.0
        ref = np.fromfile(path, np.float32).reshape(n, n, 4)
        rough.append(r)
        curves.append(ref[:, :, 0].mean(axis=1) / gain)
    order = np.argsort(rough)
    rough = np.array(rough)[order]
    curves = np.array(curves)[order]
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "src", "sheen_table.rs")
    with open(out, "w") as fh:
        fh.write("//! Generated by `lab/fit_sheen.py` from Blender 4.2 renders: EEVEE's Principled sheen albedo, row-major over\n")
        fh.write("//! roughness (rows, at ROUGH_AT) and cos_theta (columns, at NV_AT).\n\n")
        fh.write(f"pub const NV: usize = {len(rows)};\n")
        fh.write(f"pub const ROUGH: usize = {len(rough)};\n")
        fh.write("#[rustfmt::skip]\npub static NV_AT: [f32; NV] = [" + ", ".join(f"{v:.5f}" for v in rows) + "];\n")
        fh.write("pub static ROUGH_AT: [f32; ROUGH] = [" + ", ".join(f"{r:.4f}" for r in rough) + "];\n")
        fh.write("#[rustfmt::skip]\npub static SHEEN: [f32; NV * ROUGH] = [\n")
        for row in curves:
            fh.write("    " + ", ".join(f"{v:.5f}" for v in row) + ",\n")
        fh.write("];\n")
    print("wrote", out, "roughness", rough.tolist())


main()
