"""The head part: skull and face skin with eye and mouth openings, eyeballs, lashes, brows, mouth interior, ears, blush,
and the face morphs, all generated from the spec ([head] table + [proportions] + [colors]).

Overview (see the head_* modules):
  head_shape  implicit head (visual hull of a front and a side outline + blobs + neck), head-local coordinates
  head_skin   (theta, phi) grid of that shape with holes, ring zones, neck ring
  head_eye    eye opening, eyeball placement, lid rings, eyeball layers (sclera, iris, pupil, highlights)
  ...
The head is built in HEAD-LOCAL metres (origin at the head bone, Reisen-sized) and placed in model space with
`Frame(pivot, scale)`.

`[head]` keys (all optional): source ("param" (default): the face is generated by this module; "body": the face comes from
the imported base the body part publishes, see head_body), scale (default [proportions] s_head, else 1), skin / eyes
colours override [colors.*]. The generated face below is the "param" mode; `published` (the info the hair and the outfit fit
to) is shared by both modes."""
